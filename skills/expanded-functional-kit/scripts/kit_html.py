def css(th):
    d = dict(th)
    d["primary_tint"] = tint(th["primary"], 0.92)
    d["primary_line"] = tint(th["primary"], 0.6)
    return CSS % d


def page(title, subtitle, th, body, note=None):
    n = '<div class="note">%s</div>' % esc(note) if note else ""
    return ('<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            "<title>%s</title><style>%s</style></head><body>"
            '<header class="top"><h1>%s</h1><p>%s</p></header><main>%s%s</main>'
            "<footer>Generated by the expanded-functional-kit skill. Record IDs and figures marked illustrative are not customer data.</footer>"
            "</body></html>") % (esc(title), css(th), esc(title), esc(subtitle), n, body)


def tag(text, tone="grey"):
    return '<span class="tag %s">%s</span>' % (tone, esc(text))


def table(headers, rows, cls="t"):
    h = "".join("<th>%s</th>" % esc(x) for x in headers)
    b = "".join("<tr>%s</tr>" % "".join("<td>%s</td>" % (c if isinstance(c, _Raw) else esc(c)) for c in r) for r in rows)
    return '<table class="%s"><tr>%s</tr>%s</table>' % (cls, h, b)


class _Raw(str):
    """Marks a string as already-escaped HTML for table()."""


def raw(s):
    return _Raw(s)
